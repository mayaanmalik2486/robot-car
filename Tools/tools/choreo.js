// The robot's dance-step dictionary and a choreography for every song.
//
// A STEP is one bar (8 half-beats: "1 & 2 & 3 & 4 &"), written as 8 tokens:
//   .  keep doing the last move     P  stand (head bobs)     Z  FREEZE: strike a pose
//   F  forward    B  back    D  dash (full-speed hit)
//   <  spin left  >  spin right     (  twist left   )  twist right
//   [  curve forward-left   ]  curve forward-right   {  curve back-left (undoes [)   }  curve back-right (undoes ])
//   l  look left  r  look right
//   add ~ for the SOFT (smooth, slow-motion) version: F~  (~
//   add * to a spin for a ROUND spin: exactly once round, ending facing the front: <*  >*
// Every step brings the car back to where it started, facing the same way, so the
// robot dances on the spot (the checker at the bottom makes sure of it).
//
// A CHOREOGRAPHY gives each part of the song (intro, verse, chorus...) a routine:
// a list of steps, one per bar. The routine starts again every time that part comes
// back, so every chorus has the same chorus routine - like real choreography.
//   chorus_last: a bigger version for the last chorus
//   fill: the step used in the last bar before a big part (the lead-in)
//   finale: the very last bar of the song

