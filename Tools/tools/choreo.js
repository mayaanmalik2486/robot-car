// ---------------------------------------------------------------------------
const TOKENS = { '.': 'HOLD', P: 'POSE', Z: 'FREEZE', F: 'FWD', B: 'BACK', D: 'DASH', '<': 'SPIN_L', '>': 'SPIN_R',
  '(': 'TWIST_L', ')': 'TWIST_R', '[': 'SWAY_L', ']': 'SWAY_R', '{': 'BACK_L', '}': 'BACK_R', l: 'LOOK_L', r: 'LOOK_R' };

// wheel speeds (left, right) of each move, as a share of the dance speed - for the balance check
const WHEELS = { FWD: [1, 1], BACK: [-1, -1], DASH: [1.05, 1.05], SPIN_L: [-1, 1], SPIN_R: [1, -1], TWIST_L: [-0.7, 0.7], TWIST_R: [0.7, -0.7],
  SWAY_L: [0.35, 1], SWAY_R: [1, 0.35], BACK_L: [-0.35, -1], BACK_R: [-1, -0.35] };

function parseStep(name, text) {
  const toks = text.trim().split(/\s+/);
  if (toks.length !== 8) throw new Error(`step ${name}: needs 8 tokens, has ${toks.length}`);
  return toks.map((t) => {
    const soft = t.includes('~'), round = t.includes('*');
    const k = t.replace(/[~*]/g, '');
    if (!TOKENS[k]) throw new Error(`step ${name}: unknown token ${t}`);
    if (k === '.' && (soft || round)) throw new Error(`step ${name}: "." cannot be soft or round`);
    if (round && k !== '<' && k !== '>') throw new Error(`step ${name}: only spins can be round (${t})`);
    return { move: TOKENS[k], soft, round };
  });
}

// Drive the steps through a simple model of the car: where does it end up?
function travel(stepsList, start = { x: 0, y: 0, a: 0, last: null, dash: false }) {
  const s = { ...start };
  for (const steps of stepsList) for (const st of steps) {
    if (st.move !== 'HOLD') {
      s.backFull = st.move === 'BACK' && s.dash && !st.soft;   // a BACK right after a DASH snaps back at full speed
      if (!['HOLD', 'FREEZE', 'POSE', 'LOOK_L', 'LOOK_R'].includes(st.move)) s.dash = st.move === 'DASH';
      s.last = st;
    }
    const m = s.last;
    if (!m || !WHEELS[m.move] || m.round) continue;     // a ROUND spin ends facing where it started
    const k = (m.soft ? 0.6 : 1) * (m.move === 'BACK' && s.backFull ? 1.05 : 1);
    const [L, R] = WHEELS[m.move].map((w) => w * k);
    const v = (L + R) / 2, w = (R - L) / 2, N = 50;
    for (let i = 0; i < N; i++) { s.x += v / N * Math.cos(s.a); s.y += v / N * Math.sin(s.a); s.a += w / N; }
  }
  return s;
}

// The C code for one step: e.g. { FWD, HOLD, POSE+SOFT, SPIN_L+ROUND, ... }
function stepCode(steps) {
  return steps.map((st) => st.move + (st.soft ? '+SOFT' : '') + (st.round ? '+ROUND' : ''));
}

